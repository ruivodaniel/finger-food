// ============================================================
// FONTS CSS
// ============================================================

export function themeToFontsCSS(theme: Theme): string {
  const { fonts, fontSources } = theme.typography;
  const uniqueFamilies = [...new Set(Object.values(fonts))];

  const googleImports: string[] = [];
  const fontFaces: string[] = [];

  for (const family of uniqueFamilies) {
    const source = fontSources?.[family];
    if (!source) continue;

    if (source.type === 'google') {
      googleImports.push(`@import url("${source.url}");`);
    } else if (source.type === 'local') {
      for (const face of source.faces) {
        const ext = face.src.endsWith('.woff2') ? 'woff2' : 'woff';
        fontFaces.push(
          `@font-face {\n  font-family: "${family}";\n  src: url("${face.src}") format("${ext}");\n  font-weight: ${face.weight};\n  font-style: ${face.style ?? 'normal'};\n  font-display: swap;\n}`,
        );
      }
    }
  }

  const lines: string[] = [
    `/* ==========================================================================\n   PROWD Theme Fonts — ${theme.name}\n   Generated by the theme engine. Do not edit manually.\n   Import this file FIRST in your index.css, before Tailwind.\n   ========================================================================== */`,
  ];
  if (googleImports.length > 0) lines.push(googleImports.join('\n'));
  if (fontFaces.length > 0) lines.push(fontFaces.join('\n'));

  return lines.join('\n\n');
}

// ============================================================
// MAIN CSS
// ============================================================

export function themeToCSS(theme: Theme): string {
  const sections: string[] = [];

  sections.push(`/* ==========================================================================
   PROWD Theme — ${theme.name}
   Generated by the theme engine. Do not edit manually.
   ========================================================================== */`);

  sections.push(`\n/* === Tailwind Variant Declarations === */
@custom-variant dark (&:is(.dark *));`);

  const primitives: Record<string, CssVarValue> = {
    ...processColors(theme.colors),
    ...processTypography(theme),
    ...processSpacing(theme.spacing),
    ...processRadius(theme.radius),
    ...processEffects(theme),
    ...processTransitions(theme.transitions),
    ...processBorderWidths(theme.borderWidths),
    ...processIcons(theme.icons),
    ...processGradients(theme),
  };
  sections.push('\n/* === L1: Primitives === */');
  sections.push(formatVarsRule(':root', primitives));

  const modeNames = Object.keys(theme.modes.colorScheme);
  const defaultMode = modeNames[0] ?? 'light';

  sections.push('\n/* === L1b: Modes + Derivations === */');
  for (const modeName of modeNames) {
    const preset = theme.modes.colorScheme[modeName];
    if (!preset) continue;
    const modeVars = processModeVars(modeName, preset as { background: string; foreground: string; derivation: Record<string, unknown> }, theme.colors);

    if (modeName === defaultMode) {
      sections.push(formatVarsRule(':root', modeVars));
    } else {
      sections.push(formatVarsRule(`[data-mode="${modeName}"]`, modeVars));
    }
  }

  sections.push(`\n/* === Tailwind Token Registrations === */
@theme inline {
  --color-background: var(--background);
  --color-foreground: var(--foreground);
  --color-primary: var(--primary);
  --color-primary-foreground: var(--primary-foreground);
  --color-secondary: var(--secondary);
  --color-secondary-foreground: var(--secondary-foreground);
  --color-muted: var(--muted);
  --color-muted-foreground: var(--muted-foreground);
  --color-accent: var(--accent);
  --color-accent-foreground: var(--accent-foreground);
  --color-destructive: var(--destructive);
  --color-border: var(--border);
  --color-input: var(--input);
  --color-ring: var(--ring);
  --color-sidebar: var(--sidebar);
  --color-sidebar-foreground: var(--sidebar-foreground);
  --color-sidebar-primary: var(--sidebar-primary);
  --color-sidebar-primary-foreground: var(--sidebar-primary-foreground);
  --color-sidebar-accent: var(--sidebar-accent);
  --color-sidebar-accent-foreground: var(--sidebar-accent-foreground);
  --color-sidebar-border: var(--sidebar-border);
  --color-sidebar-ring: var(--sidebar-ring);
  --color-success: var(--success);
  --color-success-foreground: var(--success-foreground);
  --color-chart-1: var(--chart-1);
  --color-chart-2: var(--chart-2);
  --color-chart-3: var(--chart-3);
  --color-chart-4: var(--chart-4);
  --color-chart-5: var(--chart-5);
  --radius-sm: calc(var(--radius) - 4px);
  --radius-md: calc(var(--radius) - 2px);
  --radius-lg: var(--radius);
  --radius-xl: calc(var(--radius) + 4px);
  --font-sans: var(--typography-font-family-primary, system-ui, sans-serif);
  --font-heading: var(--typography-font-family-primary, system-ui, sans-serif);
  --font-body: var(--typography-font-family-secondary, system-ui, sans-serif);
  --font-mono: var(--typography-font-family-mono-primary, ui-monospace, monospace);
  --font-quote: var(--typography-font-family-quote, Georgia, serif);
}`);

  sections.push(`\n/* === Legacy Bridge: shadcn compat === */
:root {
  --radius: 0.625rem;
  --card: var(--background);
  --card-foreground: var(--foreground);
  --popover: var(--background);
  --popover-foreground: var(--foreground);
  --primary-foreground: var(--color-main-white);
  --secondary-foreground: var(--foreground);
  --muted-foreground: var(--color-gray-500);
  --accent-foreground: var(--foreground);
  --destructive: var(--color-status-error);
  --border: var(--color-gray-200);
  --input: var(--color-gray-200);
  --ring: var(--primary);
  --chart-1: var(--color-brand-1);
  --chart-2: var(--color-brand-2);
  --chart-3: var(--color-brand-3);
  --chart-4: var(--color-brand-4);
  --chart-5: var(--color-flat-orange);
  --sidebar: var(--background);
  --sidebar-foreground: var(--foreground);
  --sidebar-primary: var(--primary);
  --sidebar-primary-foreground: var(--color-main-white);
  --sidebar-accent: var(--color-gray-100);
  --sidebar-accent-foreground: var(--foreground);
  --sidebar-border: var(--border);
  --sidebar-ring: var(--ring);
  --success: var(--color-status-success);
  --success-foreground: var(--color-main-white);
  --container-md: 30rem;
}`);

  sections.push(`\n/* === Base Layer === */
@layer base {
  *, *::before, *::after {
    box-sizing: border-box;
    border-color: var(--border);
    outline-color: color-mix(in srgb, var(--ring) 50%, transparent);
  }

  body {
    background-color: var(--background);
    color: var(--foreground);
    font-family: var(--typography-font-family-primary, system-ui, sans-serif);
    line-height: 1.5;
    -webkit-font-smoothing: antialiased;
    -moz-osx-font-smoothing: grayscale;
  }

  input, textarea, select, button {
    font: inherit;
    color: inherit;
  }

  input, textarea, select {
    background: transparent;
    border: none;
    outline: none;
    appearance: none;
    -webkit-appearance: none;
  }

  input[type="search"]::-webkit-search-decoration,
  input[type="search"]::-webkit-search-cancel-button,
  input[type="search"]::-webkit-search-results-button,
  input[type="search"]::-webkit-search-results-decoration {
    display: none;
  }

  input[type="number"] {
    -moz-appearance: textfield;
  }
  input[type="number"]::-webkit-inner-spin-button,
  input[type="number"]::-webkit-outer-spin-button {
    -webkit-appearance: none;
  }

  textarea {
    resize: vertical;
  }

  button, [role="button"] {
    cursor: pointer;
  }

  button:disabled, input:disabled, textarea:disabled, select:disabled {
    cursor: not-allowed;
  }

  ul, ol {
    list-style: none;
    margin: 0;
    padding: 0;
  }

  img, video, svg {
    display: block;
    max-width: 100%;
  }

  h1, h2, h3, h4, h5, h6 {
    font-size: inherit;
    font-weight: inherit;
  }

  a {
    color: inherit;
    text-decoration: inherit;
  }

  p, blockquote, figure {
    margin: 0;
  }

  table {
    border-collapse: collapse;
    border-spacing: 0;
  }
}`);

  sections.push('\n/* === Typography Elements === */');
  sections.push(...generateTypographyElementRules(theme));

  sections.push('\n/* === Property Application === */');
  sections.push(generatePropertyApplication());

  sections.push('\n/* === Family & Element Extras === */');
  sections.push(...generateFamilyExtrasCSS(theme));

  const cascadeRules = processCascadeRules(theme);
  sections.push('\n/* === Cascade === */');
  sections.push(...cascadeRules);

  const layoutRules = processLayouts(theme);
  if (layoutRules.length > 0) {
    sections.push('\n/* === Layouts === */');
    sections.push(...layoutRules);
  }

  sections.push(`\n/* === Component Overrides (shadcn data-slot) === */
[data-slot="badge"] {
  box-shadow: var(--shadow-xs, 0 1px 2px rgba(0,0,0,0.05));
}
[data-slot="card"] {
  box-shadow: var(--shadow-xs, 0 1px 2px rgba(0,0,0,0.05));
}
[data-slot="card-footer"] {
  padding: 1rem;
}
[data-slot="dialog-content"] {
  max-width: 26.5rem;
}
[data-slot="dropdown-menu-separator"] {
  margin-left: 0 !important;
  margin-right: 0 !important;
}
[data-slot="form-message"] {
  text-align: start;
}
[data-slot="sheet-content"] {
  max-width: 28rem;
}
[data-slot="sheet-header"] {
  gap: 0.5rem;
  padding: 1.5rem 1.5rem 0.5rem;
}
[data-slot="sheet-title"] {
  font-size: 1.125rem;
  font-weight: 500;
}
[data-slot="sheet-footer"] {
  gap: 1rem;
  padding: 1.5rem;
}
.underline {
  text-decoration-skip-ink: none;
}
a.active {
  font-weight: 500;
}`);

  return sections.join('\n\n');
}
