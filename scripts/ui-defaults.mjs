// pnpm ui:defaults [--check]
// The default of every versioned thing of the UI library is its latest version: code that imports a thing by its folder, naming no version, gets the latest,
// as a UI document that names no version does. Each thing's index.ts is written from its version folders here: no number in it is typed by hand.
// The latest versions are evergreen: nothing in them names a version. A pin lives in an old version, which names the version of each thing it was using
// when it was the latest. PINS below holds a default back, with its reason: empty, and to stay empty.
//   --check   writes nothing; says which index.ts is not what it should be, and fails when one is
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** THE EXCEPTIONS: a thing held at a version that is not its latest, and why. Empty is the goal */
const PINS = {};

const WEB = "shared/libs/ui/web", checkOnly = process.argv.includes("--check");
const wrong = [], written = [];
for (const place of ["primitives/components", "primitives/layouts"]) {
  for (const name of readdirSync(join(WEB, place)).sort()) {
    const thing = `${place}/${name}`, dir = join(WEB, thing), index = join(dir, "index.ts");
    if (!existsSync(index)) continue;
    const versions = readdirSync(dir).map((v) => /^v(\d+)$/.exec(v)).filter((m) => m && ["index.ts", "index.tsx"].some((f) => existsSync(join(dir, m[0], f)))).map((m) => Number(m[1])).sort((a, b) => a - b);
    if (!versions.length) continue;
    const latest = versions[versions.length - 1], pin = PINS[thing];
    const version = pin ? pin.version : latest;
    const text = pin
      ? `// GENERATED by scripts/ui-defaults.mjs: never edit. PINNED at v${version}, an exception (the latest is v${latest}): ${pin.reason}.\nexport * from "./v${version}";\n`
      : `// GENERATED by scripts/ui-defaults.mjs: never edit. The default is the latest version, v${latest}.\nexport * from "./v${version}";\n`;
    if (readFileSync(index, "utf-8") === text) continue;
    if (checkOnly) wrong.push(`${thing}: its index.ts is not the one generated (default v${version})`); else { writeFileSync(index, text); written.push(`${thing} → v${version}${pin ? " (pinned)" : ""}`); }
  }
}
const pins = Object.entries(PINS);
if (checkOnly) { for (const w of wrong) console.log(w); console.log(wrong.length ? `\n${wrong.length} to regenerate: pnpm ui:defaults` : "every default is as generated"); }
else console.log(`${written.length} index.ts written`);
console.log(`${pins.length} pinned, each an exception:`); for (const [thing, p] of pins) console.log(`  ${thing} at v${p.version}: ${p.reason}`);
process.exit(checkOnly && wrong.length ? 1 : 0);
